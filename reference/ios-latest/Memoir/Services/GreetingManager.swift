    // MARK: - 公开方法

    /// 根据当前时间返回一条问候语（同一小时内固定）。
    ///
    /// **返回 `LocalizedStringKey` 而不是 `String`** —— `Text(String)` 不会走本地化，
    /// 这批文案因此在任何语言下都显示中文（2026-08-08 修）。
    /// 返回 key 之后由 `Text` 去查 catalog，并且**尊重 App 内的语言选择**
    /// （`.environment(\.locale, ...)`），这一点 `String(localized:)` 做不到 —— 它只看系统语言。
    static func timeBasedGreeting() -> LocalizedStringKey {
        let hour = Calendar.current.component(.hour, from: Date())

        let pool: [String]
        switch hour {
        case 5...8:   pool = morningGreetings
        case 9...11:  pool = morningLateGreetings
        case 12...16: pool = afternoonGreetings
        case 17...20: pool = eveningGreetings
        default:      pool = nightGreetings
        }

        let index = hour % pool.count
        return LocalizedStringKey(pool[index])
    }

    /// 根据日期返回当天的语录（同一天固定显示同一条）。
    ///
    /// ⚠️ **引号包含在译文里**，调用方不要再自己加 `「」` ——
    /// 各语言的引号形状不同（中日「」、英文 “”、法语 « »），写死一种就会出洋相。
    static func dailyQuote() -> LocalizedStringKey {
        let dayOfYear = Calendar.current.ordinality(of: .day, in: .year, for: Date()) ?? 1
        let index = (dayOfYear - 1) % dailyQuotes.count
        return LocalizedStringKey(dailyQuotes[index])
    }
